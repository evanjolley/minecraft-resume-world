/** FNV-1a, 32 bit. A fingerprint, not a security property. */
function fnv(str) {
  let h = 0x811c9dc5
  for (let i = 0; i < str.length; i++) { h ^= str.charCodeAt(i); h = Math.imul(h, 0x01000193) }
  return (h >>> 0).toString(36)
}

/**
 * Two saves of the same world, made on two devices, folded into one.
 * Edits: the union, and where both changed one coordinate `preferred` wins.
 * State (position, inventory, time): whichever was saved last.
 */
export function mergeSaves(preferred, other) {
  if (!other) return preferred
  if (!preferred) return other
  const worlds = {}
  for (const dim of new Set([...Object.keys(other.worlds ?? {}), ...Object.keys(preferred.worlds ?? {})])) {
    const a = preferred.worlds?.[dim]
    const b = other.worlds?.[dim]
    const byPos = new Map()
    for (const e of b?.edits ?? []) byPos.set(`${e[0]},${e[1]},${e[2]}`, e)
    for (const e of a?.edits ?? []) byPos.set(`${e[0]},${e[1]},${e[2]}`, e)
    const tiles = a?.tiles ?? b?.tiles
    worlds[dim] = { gen: a?.gen ?? b?.gen ?? '', edits: [...byPos.values()].slice(0, MAX_EDITS_PER_WORLD), ...(tiles ? { tiles } : {}) }
  }
  const newer = (preferred.updatedAt ?? 0) >= (other.updatedAt ?? 0) ? preferred : other
  return { v: SAVE_VERSION, updatedAt: Math.max(preferred.updatedAt ?? 0, other.updatedAt ?? 0),
    state: newer.state ?? null, worlds }
}

/* ------------------------------------------------------------------ *
 * Boot: the save, fetched before the Engine exists
 * ------------------------------------------------------------------ */

/**
 * Called by main.js BEFORE the Engine is constructed, so a saved position can
 * be the player's start and the edit list is ready before the first chunk is
 * generated.
 *
 * For a signed-in visitor it also asks the server, with a short timeout, and
 * takes whichever save is newer. Guests never wait on the network.
 *
 * @returns {Promise<null | { record, save }>}
 */
export async function loadSave(account, { timeoutMs = 2500 } = {}) {
  if (!persistenceEnabled()) return null
  let record = await readLocal()
  // A save written by a different visitor is not a signed-in visitor's
  // world. Guests keep whatever is local even if their session id was
  // re-minted (an expired token), since sign-in and sign-out already clear
  // the local save on purpose and nothing else should.
  if (record && account.state.account && record.owner && record.owner !== account.state.visitor) {
    record = null
  }
  if (account.enabled && account.state.account) {
    const remote = await Promise.race([
      account.call('/api/world', { method: 'GET' }).catch(() => null),
      new Promise((r) => setTimeout(() => r(null), timeoutMs)),
    ])
    if (remote?.ok && remote.data?.save && remote.data.rev > (record?.syncedRev ?? 0)) {
      const save = record?.dirty ? mergeSaves(record.save, remote.data.save) : remote.data.save
      record = { save, syncedRev: remote.data.rev, dirty: !!record?.dirty, owner: account.state.visitor }
      await writeLocal(record)
    }
  }
  return record?.save?.v === SAVE_VERSION ? { record, save: record.save } : null
}

/* ------------------------------------------------------------------ *
 * The live recorder
 * ------------------------------------------------------------------ */

/**
 * Installed right after registerBlocks, before the first chunk is requested.
 *
 * @param {object} noa
 * @param {object} deps
 * @param {Record<string, number>} deps.ids        block key -> engine id
 * @param {Function} deps.getVoxelID               the generator
 * @param {() => string} deps.currentDimension     which world getVoxelID answers for
 * @param {{record, save} | null} deps.loaded      what loadSave returned
 * @param {object} deps.account                    src/account.js
 */
export function installPersistence(noa, { ids, getVoxelID, currentDimension, loaded, account }) {
  const enabled = persistenceEnabled()
  const keyOf = new Map(Object.entries(ids).map(([k, id]) => [id, k]))
  keyOf.set(0, 'air')
  const idOf = (key) => (key === 'air' ? 0 : ids[key])

  /* dim -> Map<"x,y,z", {x,y,z,to,was}> and dim -> Map<chunkKey, Set<"x,y,z">> */
  const edits = new Map()
  const chunks = new Map()
  const gens = new Map()
  /* The fingerprint each saved world was recorded against, kept for worlds not
   * visited this session so a resave does not blank them. */
  const savedGens = new Map(Object.entries(loaded?.save?.worlds ?? {}).map(([d, w]) => [d, w.gen]))
  let record = loaded?.record ?? { save: null, syncedRev: 0, dirty: false, owner: null }
  let dirty = false
  let changedSinceSync = !!record.dirty
  let dropped = 0
  let lastSnapshot = loaded?.save?.state ?? null

  const chunkKey = (x, y, z) => `${Math.floor(x / CHUNK)},${Math.floor(y / CHUNK)},${Math.floor(z / CHUNK)}`
  const worldOf = (dim) => {
    if (!edits.has(dim)) { edits.set(dim, new Map()); chunks.set(dim, new Map()) }
    return edits.get(dim)
  }

  function put(dim, x, y, z, to, was) {
    const list = worldOf(dim)
    const pos = `${x},${y},${z}`
    const ck = chunkKey(x, y, z)
    const index = chunks.get(dim)
    if (to === was) {
      list.delete(pos)
      index.get(ck)?.delete(pos)
      return
    }
    if (!list.has(pos) && list.size >= MAX_EDITS_PER_WORLD) return
    const prev = list.get(pos)
    if (prev) { prev.to = to; return }
    list.set(pos, { x, y, z, to, was })
    if (!index.has(ck)) index.set(ck, new Set())
    index.get(ck).add(pos)
  }

  /** The terrain's fingerprint: a coarse sample of block KEYS around the surface. */
  function generationId() {
    const dim = currentDimension()
    if (gens.has(dim)) return gens.get(dim)
    let sample = dim
    try {
      const b = bounds(dim)
      for (let x = b.minX; x <= b.maxX; x += 16) {
        for (let z = b.minZ; z <= b.maxZ; z += 16) {
          for (let y = 40; y < 200; y += 8) sample += keyOf.get(getVoxelID(x, y, z, ids)) ?? '?'
        }
      }
    } catch { sample += 'unavailable' }
    const gen = `g1-${fnv(sample)}`
    gens.set(dim, gen)
    return gen
  }

  /* Load the saved edits, translating keys to this build's ids. */
  if (enabled && loaded?.save) {
    for (const [dim, w] of Object.entries(loaded.save.worlds ?? {})) {
      for (const [x, y, z, toKey, wasKey] of w.edits ?? []) {
        const to = idOf(toKey), was = idOf(wasKey)
        if (to === undefined || was === undefined) { dropped++; continue }
        put(dim, x, y, z, to, was)
      }
    }
  }

  /*
   * Was the saved position made in THIS landscape? Compared now, before the
   * first tick, so a moved world puts you at spawn instead of inside a hill.
   */
  const savedState = loaded?.save?.state ?? null
  const savedGen = loaded?.save?.worlds?.[savedState?.dimension ?? 'overworld']?.gen
  const positionTrusted = !!savedState?.position
    && (savedState.dimension ?? 'overworld') === 'overworld'
    && (!savedGen || savedGen === (enabled ? generationId() : savedGen))

  /* ---- catch every voxel write ---- */

  let recording = enabled
  if (enabled) {
    const world = noa.world
    const inner = world.setBlockID.bind(world)
    world.setBlockID = function (id, x, y, z) {
      const out = inner(id, x, y, z)
      /*
       * Keyed by island.js's dimension, NOT noa.worldName: noa boots with
       * worldName 'default' and only dimensions.js renames it, so the two
       * strings differ in the overworld. The generator's own name is the one
       * that says which generator `was` came from.
       */
      if (recording && world.getBlockID(x, y, z) === id) {
        const dim = currentDimension()
        let was
        try { was = getVoxelID(x, y, z, ids) } catch { was = undefined }
        if (was !== undefined) {
          put(dim, x, y, z, id, was)
          dirty = true
          changedSinceSync = true
        }
      }
      return out
    }
  }

  /**
   * Called from main.js's worldDataNeeded handler after the generator has
   * filled `data`. Applies this chunk's edits, checking each against what the
   * generator just produced (see the header).
   */
  function overlayChunk(data, x0, y0, z0) {
    if (!enabled) return
    // The dimension whose generator just filled `data`; see the note on
    // worldName in the recorder above.
    const dim = currentDimension()
    const index = chunks.get(dim)
    if (!index) return
    const set = index.get(chunkKey(x0, y0, z0))
    if (!set || !set.size) return
    const list = edits.get(dim)
    for (const pos of [...set]) {
      const e = list.get(pos)
      const i = e.x - x0, j = e.y - y0, k = e.z - z0
      if (i < 0 || j < 0 || k < 0 || i >= data.shape[0] || j >= data.shape[1] || k >= data.shape[2]) continue
      if (data.get(i, j, k) !== e.was) {
        // The landscape moved under this edit. It describes nothing now, and
        // neither does any sign text, painting or furnace restored onto it.
        list.delete(pos)
        set.delete(pos)
        if (signTextAt(e.x, e.y, e.z) && !baselineSigns.has(pos)) clearSignText(e.x, e.y, e.z)
        if (paintingEntries().some(([k]) => k === pos)) clearPainting(e.x, e.y, e.z)
        furnaces?.forget([e.x, e.y, e.z])
        dropped++
        dirty = true
        changedSinceSync = true
        continue
      }
      data.set(i, j, k, e.to)
    }
  }

  /* ------------------------------------------------------------------ *
   * Saving
   * ------------------------------------------------------------------ */

  let collectState = () => lastSnapshot

  /* ------------------------------------------------------------------ *
   * Tile data: sign text, paintings, furnace contents
   * ------------------------------------------------------------------ *
   *
   * A voxel is an integer, so what a block HOLDS lives in side tables keyed
   * by coordinate (signText.js, paintingArt.js, furnace.js). The overlay
   * restores the blocks without going through setBlock, so those tables have
   * to be restored separately or a saved sign comes back blank and a placed
   * painting comes back with no picture.
   *
   * The same diff discipline as blocks. The builds write their own signs and
   * paintings every time the world is generated, so only what the VISITOR
   * changed is saved:
   *
   *   - anything at a coordinate the visitor edited (a sign they placed, a
   *     painting they hung, a furnace they built), and
   *   - a build's sign whose text they rewrote, found by comparing with the
   *     baseline the builds produced at boot, and
   *   - a TOMBSTONE for a build's sign or painting the visitor removed, so it
   *     does not float back as text over an empty block.
   *
   * Restored only where it still makes sense: an entry whose block edit was
   * dropped because the landscape moved (see the header) is dropped with it.
   */
  let furnaces = null
  let baselineSigns = new Map()
  let baselinePaintings = new Set()
  const savedTiles = new Map(Object.entries(loaded?.save?.worlds ?? {})
    .filter(([, w]) => w.tiles).map(([d, w]) => [d, w.tiles]))
  const posKey = (x, y, z) => `${x},${y},${z}`
  const parsePos = (k) => k.split(',').map(Number)
  const edited = (dim, k) => edits.get(dim)?.has(k) ?? false
  const stackOut = (s) => {
    if (!s) return null
    const key = item(s.id)?.key
    return key ? { key, count: s.count } : null
  }
  const stackIn = (s) => {
    if (!s) return null
    const id = itemId(s.key)
    return id === undefined || id === null ? null : { id, count: s.count }
  }

  function captureBaseline() {
    baselineSigns = new Map(signTextEntries().map(([k, e]) => [k, JSON.stringify(e)]))
    baselinePaintings = new Set(paintingEntries().map(([k]) => k))
  }

  function collectTiles(dim) {
    const signs = []
    const live = new Set()
    for (const [k, e] of signTextEntries()) {
      live.add(k)
      if (edited(dim, k) || baselineSigns.get(k) !== JSON.stringify(e)) {
        signs.push([...parsePos(k), e.lines.map((l) => String(l).slice(0, 64)), e.colour ?? null])
      }
    }
    const paintings = []
    const hungNow = new Set()
    for (const [k, e] of paintingEntries()) {
      hungNow.add(k)
      if (edited(dim, k) && !baselinePaintings.has(k)) paintings.push([...parsePos(k), e.facing, e.name])
    }
    const cleared = [
      ...[...baselineSigns.keys()].filter((k) => !live.has(k)).map((k) => ['sign', ...parsePos(k)]),
      ...[...baselinePaintings].filter((k) => !hungNow.has(k)).map((k) => ['painting', ...parsePos(k)]),
    ]
    const ovens = []
    for (const { pos, f } of furnaces?.all() ?? []) {
      if (!f.slots.some(Boolean) && f.burn <= 0) continue
      ovens.push([...parsePos(pos), f.kind, f.slots.map(stackOut), f.burn, f.burnTotal, f.cook, f.cookTotal])
    }
    return { signs, paintings, furnaces: ovens, cleared }
  }

  function restoreTiles(dim) {
    const t = savedTiles.get(dim)
    if (!t) return 0
    let n = 0
    for (const [kind, x, y, z] of t.cleared ?? []) {
      if (kind === 'sign') clearSignText(x, y, z)
      else if (kind === 'painting') clearPainting(x, y, z)
    }
    for (const [x, y, z, lines, colour] of t.signs ?? []) {
      const k = posKey(x, y, z)
      if (!edited(dim, k) && !signTextAt(x, y, z)) continue
      setSignText(x, y, z, lines, colour ? { colour } : {})
      n++
    }
    for (const [x, y, z, facing, name] of t.paintings ?? []) {
      if (!edited(dim, posKey(x, y, z))) continue
      try { registerPainting(x, y, z, facing, name); n++ } catch { /* that art no longer exists */ }
    }
    for (const [x, y, z, kind, slots, burn, burnTotal, cook, cookTotal] of t.furnaces ?? []) {
      if (!furnaces) break
      const k = posKey(x, y, z)
      if (!edited(dim, k) && !String(keyOf.get(getVoxelID(x, y, z, ids)) ?? '').includes('furnace')) continue
      const f = furnaces.at([x, y, z], kind)
      f.slots = (slots ?? []).slice(0, 3).map(stackIn)
      while (f.slots.length < 3) f.slots.push(null)
      Object.assign(f, { burn: burn ?? 0, burnTotal: burnTotal ?? 0, cook: cook ?? 0, cookTotal: cookTotal ?? f.cookTotal })
      n++
    }
    return n
  }

  function buildSave() {
    const worlds = {}
    for (const [dim, list] of edits) {
      const out = []
      for (const e of list.values()) {
        const to = keyOf.get(e.to), was = keyOf.get(e.was)
        if (to && was) out.push([e.x, e.y, e.z, to, was])
      }
      worlds[dim] = { gen: gens.get(dim) ?? (dim === currentDimension() ? generationId() : savedGens.get(dim) ?? ''), edits: out }
    }
    if (!worlds.overworld) worlds.overworld = { gen: currentDimension() === 'overworld' ? generationId() : '', edits: [] }
    const here = currentDimension()
    if (!worlds[here]) worlds[here] = { gen: generationId(), edits: [] }
    /* Tile data: live for the world you are in, as loaded for the others. */
    for (const dim of Object.keys(worlds)) {
      const tiles = dim === here ? collectTiles(dim) : savedTiles.get(dim)
      if (tiles) worlds[dim].tiles = tiles
    }
    lastSnapshot = collectState() ?? lastSnapshot
    return { v: SAVE_VERSION, updatedAt: Date.now(), state: lastSnapshot, worlds }
  }

  let saving = null
  async function saveLocal() {
    if (!enabled || !recording) return false
    if (saving) return saving
    saving = (async () => {
      record = { save: buildSave(), syncedRev: record.syncedRev ?? 0, dirty: changedSinceSync || dirty,
        owner: account?.state.visitor ?? record.owner ?? null }
      changedSinceSync = record.dirty
      dirty = false
      return writeLocal(record)
    })()
    try { return await saving } finally { saving = null }
  }

  /** Push to the server, merging on a conflict. Accounts only. */
  async function sync({ keepalive = false } = {}) {
    if (!enabled || !recording || !account?.enabled || !account.state.account) return { ok: false, skipped: true }
    if (!changedSinceSync && record.syncedRev) return { ok: true, skipped: true }
    const save = buildSave()
    const send = (baseRev, s) => account.call('/api/world', { method: 'PUT', body: { baseRev, save: s }, keepalive })
    try {
      let res = await send(record.syncedRev ?? 0, save)
      let final = save
      if (res.status === 409 && res.data) {
        final = mergeSaves(save, res.data.save)
        res = await send(res.data.rev, final)
      }
      if (!res.ok) return { ok: false, status: res.status }
      changedSinceSync = false
      record = { save: final, syncedRev: res.data.rev, dirty: false, owner: account.state.visitor }
      await writeLocal(record)
      return { ok: true, rev: res.data.rev }
    } catch (e) {
      return { ok: false, error: e?.message }
    }
  }

  /* ------------------------------------------------------------------ *
   * attach: everything that needs the rest of the game to exist
   * ------------------------------------------------------------------ */

  /**
   * @param {object} game
   * @returns {{ restored: boolean }}
   */
  function attach({ inventory, sky, authority, dimensions, teleport, spawn, playerEntity, camera }) {
    furnaces = inventory.furnaces ?? null
    // What the builds wrote, before the visitor or the save touches anything.
    captureBaseline()
    if (enabled) restoreTiles(currentDimension())
    collectState = () => {
      const pos = noa.ents.getPosition(playerEntity())
      const stack = (s) => {
        if (!s) return null
        const key = item(s.id)?.key
        return key ? { key, count: s.count } : null
      }
      return {
        dimension: currentDimension(),
        position: pos.map((v) => Math.round(v * 100) / 100),
        heading: camera.heading, pitch: camera.pitch,
        gamemode: authority.gamemode,
        time: sky.getTime(),
        inventory: {
          slots: inventory.slots.map(stack), armor: inventory.armor.map(stack),
          offhand: inventory.offhand.map(stack), selected: inventory.selected,
        },
      }
    }

    let restored = false
    const st = enabled ? savedState : null
    if (st) {
      restored = true
      const unstack = (s) => {
        if (!s) return null
        const id = itemId(s.key)
        return id === undefined || id === null ? null : { id, count: s.count }
      }
      const inv = st.inventory
      if (inv) {
        inv.slots?.forEach((s, i) => { if (i < inventory.slots.length) inventory.slots[i] = unstack(s) })
        inv.armor?.forEach((s, i) => { if (i < inventory.armor.length) inventory.armor[i] = unstack(s) })
        inv.offhand?.forEach((s, i) => { if (i < inventory.offhand.length) inventory.offhand[i] = unstack(s) })
        if (Number.isInteger(inv.selected)) inventory.selected = inv.selected
        inventory.emitChange()
      }
      if (typeof st.time === 'number') sky.setTime(st.time)
      if (typeof st.heading === 'number') camera.heading = st.heading
      if (typeof st.pitch === 'number') camera.pitch = st.pitch
      // Game modes are granted, not assigned: only an operator gets back
      // into a mode the authority would have to grant.
      if (st.gamemode && st.gamemode !== authority.gamemode && authority.isOperator()) {
        authority.requestGamemode(st.gamemode)
      }
      if (st.dimension && st.dimension !== 'overworld' && dimensions?.enter) {
        dimensions.enter(st.dimension).then((r) => {
          if (r?.ok) restoreTiles(st.dimension)
          // generationId() now answers for the dimension just entered.
          if (r?.ok && st.position && savedGen === generationId()) teleport(...st.position)
        })
      } else if (!positionTrusted) {
        teleport(...spawn)
      }
    }

    // Snapshot the inventory as it changes, the rest on a timer.
    inventory.onChange?.(() => { dirty = true; changedSinceSync = true })
    if (enabled) {
      setInterval(() => { saveLocal() }, LOCAL_SAVE_MS)
      setInterval(() => { sync() }, SYNC_MS)
      const flush = () => { saveLocal(); sync({ keepalive: true }) }
      document.addEventListener('visibilitychange', () => { if (document.hidden) flush() })
      addEventListener('pagehide', flush)
    }
    return { restored }
  }

  return {
    enabled,
    overlayChunk,
    attach,
    saveLocal,
    sync,
    buildSave,
    generationId,
    /** The saved player start, or null to use spawn. Read before the Engine. */
    get positionTrusted() { return positionTrusted },
    get dropped() { return dropped },
    editCount(dim = currentDimension()) { return edits.get(dim)?.size ?? 0 },
    /** The tile data a save would carry for the world you are in. */
    tiles: () => collectTiles(currentDimension()),
    /** Stop recording AND saving: sign-out wipes the save, and a pagehide
     *  flush after that must not write it straight back. */
    pause() { recording = false },
    resume() { recording = enabled },
    get record() { return record },
  }
}

/** The start position for the Engine, before persistence is installed. */
export function savedStart(loaded, fallback) {
  const st = loaded?.save?.state
  if (!persistenceEnabled() || !st?.position || (st.dimension ?? 'overworld') !== 'overworld') return fallback
  return st.position
}
