/*
 * A WORLD THAT STAYS CHANGED.
 *
 * Break a block, close the tab, come back: it is still broken, you are
 * standing where you were, holding what you held, at the same time of day.
 * docs/FUTURE.md 1c is the design this builds; docs/decisions.md has the
 * storage choice and the cost math.
 *
 * LOCAL FIRST. The save lives in IndexedDB, written every few seconds, so it
 * works for guests, works offline, and costs the server nothing. A visitor
 * who signs in (src/account.js) also syncs it to their Durable Object, which
 * is what carries it to another device.
 *
 * THE DIFF, NOT THE WORLD. The generator answers every voxel the same way on
 * every load, so only blocks that DIFFER from it are stored: a coordinate,
 * the block now there, and the block the generator put there.
 *
 * HOW A SAVE SURVIVES THE LANDSCAPE CHANGING UNDER IT. The world is being
 * regenerated by other work while saves already exist. Each edit carries
 * `was`, the generator's block at that coordinate when the edit was made, and
 * an edit is replayed only where the generator STILL produces `was`. Where
 * the landscape moved, the edit no longer describes anything that exists and
 * is dropped quietly; everywhere the landscape did not move, it survives.
 * That is finer than versioning the whole save by one generation id, which
 * would throw away every edit in the world because a tree moved somewhere
 * else. A generation id IS still recorded per world (`gen`, a fingerprint of
 * the terrain), and it does one job: if it changed, your saved POSITION is
 * not trusted and you arrive at spawn, since "where you were standing" means
 * nothing in a different landscape.
 *
 * WHERE EDITS ARE CAUGHT AND REPLAYED. Caught at noa.world.setBlockID, the
 * lowest write in the engine, so mining, placing, /fill, flowing water, a
 * torch falling off a wall and every setBlock wrapper above are all seen with
 * the id that actually landed. Replayed inside the chunk generator
 * (main.js's worldDataNeeded handler calls overlayChunk), so a restored block
 * is part of the chunk the first time it is meshed: no setBlock storm at
 * boot, no item drops, no fluid ticks, no second mesh.
 *
 * TILE DATA (sign text, which painting hangs where, furnace contents) is
 * saved per world as `tiles`; see "Tile data" below. NOT saved: AI Evan's
 * position, which resets to the door on every visit on purpose.
 *
 * UNDER AUTOMATION it is OFF unless the page opts in with
 * localStorage['world:persist'] = '1'. The suite shares one booted world
 * across ~900 tests and resets it between them; a world that remembered
 * every spec's edits across reloads would change what every reload-based
 * spec measures. test/61-persistence.spec.js opts in.
 */

export const SAVE_VERSION = 1
const DB_NAME = 'world'
const STORE = 'saves'
const SLOT = 'local'
/* Matches worker/world/save.js. Beyond this the oldest edits are kept and new
 * ones are refused rather than the save silently failing to sync. */
export const MAX_EDITS_PER_WORLD = 40_000
const CHUNK = 32
const LOCAL_SAVE_MS = 4_000
const SYNC_MS = 30_000

export function persistenceEnabled(storage = globalThis.localStorage) {
  try {
    if (storage?.getItem('world:persist') === '0') return false
    if (!globalThis.navigator?.webdriver) return true
    return storage?.getItem('world:persist') === '1'
  } catch { return false }
}

/* ------------------------------------------------------------------ *
 * IndexedDB, three calls' worth
 * ------------------------------------------------------------------ */

function openDb() {
  return new Promise((resolve, reject) => {
    if (!globalThis.indexedDB) return reject(new Error('no IndexedDB'))
    const req = indexedDB.open(DB_NAME, 1)
    req.onupgradeneeded = () => req.result.createObjectStore(STORE)
    req.onsuccess = () => resolve(req.result)
    req.onerror = () => reject(req.error)
  })
}

async function idb(mode, fn) {
  const db = await openDb()
  try {
    return await new Promise((resolve, reject) => {
      const tx = db.transaction(STORE, mode)
      const req = fn(tx.objectStore(STORE))
      tx.oncomplete = () => resolve(req?.result)
      tx.onerror = () => reject(tx.error)
      tx.onabort = () => reject(tx.error)
    })
  } finally { db.close() }
}

/** @returns {Promise<null | { save, syncedRev, dirty, owner }>} */
export async function readLocal() {
  try { return (await idb('readonly', (s) => s.get(SLOT))) ?? null } catch { return null }
}
export async function writeLocal(record) {
  try { await idb('readwrite', (s) => s.put(record, SLOT)); return true } catch { return false }
}
export async function clearLocal() {
  try { await idb('readwrite', (s) => s.delete(SLOT)); return true } catch { return false }
}

