/**
 * The suffix that marks a block generated by `nonCubeSet()`. Same regex as
 * sounds.js's, and for the same reason: a slab must never be classified by
 * the word "slab", it must be classified as whatever its source cube is.
 */
const NON_CUBE_SUFFIX = /_(slab|slab_top|stairs)$|_stairs_(north|south|east|west)_(top|bottom)$/

/** Which tab claims this item key, as `{ tab, why }`, or null if none does. */
export function ruleFor(key) {
  for (const [pattern, tab, why] of RULES) if (pattern.test(key)) return { tab, why }
  const stripped = key.replace(NON_CUBE_SUFFIX, '')
  if (stripped !== key) {
    /*
     * A family prefix is one of two things, exactly as in sounds.js. Usually
     * it names a block the rules already answer (`deepslate_brick`,
     * `smooth_sandstone`). For the eight wood families it is the bare wood
     * (`oak`, `cherry`), which names no block, so it is asked again as
     * `<wood>_planks` -- the cube nonCubeSet() actually built it from.
     */
    const inherited = ruleFor(stripped) ?? ruleFor(`${stripped}_planks`)
    if (inherited) return { tab: inherited.tab, why: `${inherited.why} (from ${stripped})` }
  }
  return null
}

