/*
 * The creative item picker: which tab every item lives in.
 *
 * This file is the CATEGORISATION. The screen that draws it lives at the
 * bottom; the interesting half is above it, and the interesting half is a
 * table of ordered rules rather than 508 hand-written lines.
 *
 * WHY RULES. This codebase has twice shipped a lookup with a handful of
 * entries and a catch-all default, and both times the default was a bug you
 * could see: sounds.js defaulted to `stone`, so leaves and snow crunched like
 * rock, and `dropFor` defaulted to self, so every ore dropped itself. Both are
 * now ordered rules over the block KEY with no catch-all and a report of what
 * matched nothing, asserted empty by a test. That is the pattern here, for the
 * same reason -- a "Miscellaneous" tab is a default with a friendly name, and
 * the day somebody adds a block, they would never find out it landed there.
 *
 * So: `uncategorisedItems()` lists every registered item no rule claims, and
 * test/31-creative.spec.js fails on a non-empty list.
 *
 * WHAT THE RULES MATCH. The item key, which for a block item is the block key.
 * Keys are generated by blocks.js in whole families (`dyed()`, `woodSet()`,
 * `nonCubeSet()`), so the naming convention IS the categorisation: every dyed
 * wool ends in `_wool`, every stair in `_stairs`, every stripped log starts
 * `stripped_`. Rejected: a `tab:` field on each block definition. It is the
 * most direct expression of this and it is 508 edits in another agent's file,
 * and it would not have caught the case these rules exist to catch -- a new
 * block arriving with no field set looks exactly like a block that matched no
 * rule, except nothing is watching.
 */

